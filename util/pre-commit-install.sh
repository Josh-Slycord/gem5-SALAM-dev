set -euo pipefail

usage() {
    echo "Usage: bash util/pre-commit-install.sh --install"
    echo "Opt in to pre-commit and gem5 commit-message hooks in this checkout."
    echo "No arguments or --help only displays this message; no hooks are changed."
}

case "${1:-}" in
    ""|--help|-h) usage; exit 0 ;;
    --install) ;;
    *) usage >&2; exit 2 ;;
esac
if [ "$#" -ne 1 ]; then
    usage >&2
    exit 2
fi

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" >/dev/null 2>&1 && pwd)"
GEM5_ROOT="${DIR}/.."
cd "${GEM5_ROOT}"

if ! command -v pre-commit >/dev/null 2>&1; then
    echo "Cannot find pre-commit. Install the maintained CI/development requirements first." >&2
    echo "No hooks were changed; no fallback hooks are installed." >&2
    exit 1
fi
if git --no-optional-locks -c core.fsmonitor=false config --get core.hooksPath >/dev/null; then
    echo "core.hooksPath is configured; manage those hooks explicitly. No hooks were changed." >&2
    exit 1
fi

# git resolves the common hook directory for both ordinary and linked worktrees.
HOOKS_DIR="$(git --no-optional-locks -c core.fsmonitor=false rev-parse --git-path hooks)"
for hook in pre-commit commit-msg; do
    target="${HOOKS_DIR}/${hook}"
    if [ -e "${target}" ] || [ -L "${target}" ]; then
        if [ -L "${target}" ] || [ ! -f "${target}" ] ||
            ! grep -Fq 'File generated by pre-commit: https://pre-commit.com' "${target}"; then
            echo "Existing ${hook} hook is not managed by pre-commit; preserve and integrate it manually." >&2
            echo "No hooks were changed." >&2
            exit 1
        fi
    fi
done

# pre-commit manages index snapshots and unstaged-change restoration. Do not
# replace it with a working-tree-only parser or overwrite custom hooks.
pre-commit install --hook-type pre-commit --hook-type commit-msg
